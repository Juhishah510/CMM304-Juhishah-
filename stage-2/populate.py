"""Generate stage-2/knowledge-graph.ttl from stage-2/data/jobs.csv.

Standard library only. Run from the repository root:
    python stage-2/populate.py
"""
import csv
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
CSV_PATH = HERE / "data" / "jobs.csv"
OUT_PATH = HERE / "knowledge-graph.ttl"

SKILLS = {
    "Communication": "Communication",
    "Teamwork": "Teamwork",
    "TimeManagement": "Time management",
    "CustomerService": "Customer service",
    "CashHandling": "Cash handling",
    "FoodHygiene": "Food hygiene",
    "Multitasking": "Multitasking",
    "ProblemSolving": "Problem solving",
    "PhysicalStamina": "Physical stamina",
    "Numeracy": "Numeracy",
}
SCHEDULES = {
    "EveningSchedule": "Evening schedule",
    "WeekendSchedule": "Weekend schedule",
    "FlexibleSchedule": "Flexible schedule",
}
EMPLOYERS = {
    "BrewHouseCafe": "BrewHouse Cafe",
    "NorthernThreads": "Northern Threads",
    "HarbourKitchen": "Harbour Kitchen",
}
LOCATIONS = {
    "Aberdeen": "Aberdeen, Scotland",
    "Dundee": "Dundee, Scotland",
    "Glasgow": "Glasgow, Scotland",
    "Edinburgh": "Edinburgh, Scotland",
}
JOB_TYPES = {"Barista", "RetailAssistant", "KitchenAssistant", "Waiter", "DeliveryDriver"}

HEADER = """@prefix sj:   <http://example.org/studentjobs#> .
@prefix owl:  <http://www.w3.org/2002/07/owl#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .

# Generated by stage-2/populate.py from stage-2/data/jobs.csv. Do not edit by hand.
# Load together with studentjobs.ttl.
# NOTE: current CSV rows are illustrative test data, not verified live job adverts.
"""


def lit(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = [HEADER]

    for local, label in SKILLS.items():
        lines.append(f"sj:{local} a sj:Skill ; rdfs:label {lit(label)}@en .")
    for local, label in SCHEDULES.items():
        lines.append(f"sj:{local} a sj:WorkSchedule ; rdfs:label {lit(label)}@en .")
    for local, label in EMPLOYERS.items():
        lines.append(f"sj:{local} a sj:Employer ; rdfs:label {lit(label)}@en .")
    for local, label in LOCATIONS.items():
        lines.append(f"sj:{local} a sj:Location ; rdfs:label {lit(label)}@en .")

    # Without the unique name assumption a reasoner cannot count distinct
    # skills, so declare the individuals different.
    for group in (SKILLS, SCHEDULES, EMPLOYERS, LOCATIONS):
        members = " ".join(f"sj:{k}" for k in group)
        lines.append(f"[] a owl:AllDifferent ; owl:distinctMembers ( {members} ) .")
    lines.append("")

    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            job_type = row["type"]
            if job_type not in JOB_TYPES:
                raise ValueError(f"Unknown job type {job_type!r} in row {row['id']}")
            if row["employer"] not in EMPLOYERS:
                raise ValueError(f"Unknown employer {row['employer']!r} in row {row['id']}")
            if row.get("location") not in LOCATIONS:
                raise ValueError(f"Unknown Scottish location {row.get('location')!r} in row {row['id']}")
            if row["schedule"] not in SCHEDULES:
                raise ValueError(f"Unknown schedule {row['schedule']!r} in row {row['id']}")
            skills = [s for s in row["skills"].split(";") if s]
            for s in skills:
                if s not in SKILLS:
                    raise ValueError(f"Unknown skill {s!r} in row {row['id']}")
            skill_list = " , ".join(f"sj:{s}" for s in skills)
            exp = row["requires_experience"].strip().lower()
            if exp not in ("true", "false"):
                raise ValueError(f"requires_experience must be true/false in row {row['id']}")
            lines.append(
                f"sj:{row['id']} a sj:{job_type} ;\n"
                f"    sj:jobTitle {lit(row['title'])} ;\n"
                f"    sj:offeredBy sj:{row['employer']} ;\n"
                f"    sj:hasSchedule sj:{row['schedule']} ;\n"
                f"    sj:locatedIn sj:{row['location']} ;\n"
                f"    sj:requiresSkill {skill_list} ;\n"
                f'    sj:hourlyPay "{row["hourly_pay"]}"^^xsd:decimal ;\n'
                f'    sj:hoursPerWeek "{row["hours_per_week"]}"^^xsd:integer ;\n'
                f'    sj:requiresExperience "{exp}"^^xsd:boolean .\n'
            )

    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
